export function translate(language: Language, key: TranslationKey, vars: Vars = {}): string {
  const template = (language === 'fa' ? fa : en)[key] as string
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`))
}

interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, vars?: Vars) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)
const STORAGE_KEY = 'ds2api-language'

export function getStoredLanguage(): Language {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'fa' ? 'fa' : 'en'
  } catch {
    return 'en'
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getStoredLanguage)
  const t = useCallback((key: TranslationKey, vars?: Vars) => translate(language, key, vars), [language])

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === 'fa' ? 'rtl' : 'ltr'
    try {
      localStorage.setItem(STORAGE_KEY, language)
    } catch {
      // The UI still works when browser storage is unavailable.
    }
  }, [language])

  const value = useMemo(() => ({ language, setLanguage, t }), [language, t])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useLanguage must be used inside LanguageProvider')
  return value
}
